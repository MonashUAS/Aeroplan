"""One-page summary of an aircraft as Markdown (`aeroplan show <aircraft> --md <out>`).

The source tree `aircraft/<aircraft>/` is the SSOT and only spokes write it. The summary is a generated view and goes
to `docs/reference/aircraft/<aircraft>.md`. Nothing in it is typed by hand.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from . import adh_doc, assets
from .build import placeholders


def _num(q: Optional[Dict[str, Any]], fmt: str = "{:.4g}") -> str:
    if not q or q.get("value") is None:
        return "-"
    return fmt.format(q["value"]) + (f" {q['units']}" if q.get("units") else "")


def _xyz(v: List[float]) -> str:
    return "(" + ", ".join(f"{x:.4f}" for x in v) + ")"


def _table(head: List[str], rows: List[List[str]]) -> List[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out + [""]


def _planforms(doc: Dict[str, Any]) -> List[List[str]]:
    rows = []
    for _path, item, _parent in adh_doc.iter_nodes(doc):
        pf = (item.get("muas") or {}).get("planform")
        if not pf or not pf.get("sections"):
            continue
        s = pf["sections"]
        half = max(x["y"] for x in s)
        area = sum(0.5 * (a["chord"] + b["chord"]) * (b["y"] - a["y"]) for a, b in zip(s, s[1:]))
        k = 2 if pf.get("symmetric") and pf.get("two_sided", True) else 1
        rows.append([pf.get("surface_name", "?"), pf.get("kind", "?"), f"{k * half:.3f}" if k == 2 else f"{half:.3f}",
                     f"{k * area:.4f}", f"{s[0]['chord']:.3f}", f"{s[-1]['chord']:.3f}",
                     "yes" if pf.get("placeholder") else "no"])
    return rows


def _propellers(doc: Dict[str, Any]) -> List[List[str]]:
    rows = []
    for _path, item, _parent in adh_doc.iter_nodes(doc):
        pr = (item.get("muas") or {}).get("propeller")
        if pr:
            rows.append([str((item.get("muas") or {}).get("instance", item.get("name", "?"))), pr.get("role", "?"),
                         str(pr.get("motor", "-")), _xyz(pr["hub"]["xyz"]), pr.get("spin", "-"), _num(pr.get("diameter"))])
    return rows


def _systems(doc: Dict[str, Any]) -> List[Dict[str, Any]]:
    seen, out = set(), []
    for _path, item, _parent in adh_doc.iter_nodes(doc):
        ps = (item.get("muas") or {}).get("propulsion_system")
        if ps and ps["system_id"] not in seen:
            seen.add(ps["system_id"])
            out.append(ps)
    return out


def aircraft_markdown(acft) -> str:
    """The summary of the aircraft `acft` (a source_tree.Aircraft) as a Markdown text."""
    doc = acft.doc
    name = acft.name
    build = (doc.get("muas") or {}).get("build") or {}
    try:
        air = adh_doc.node(doc, "1.2")
    except KeyError:
        air = {}
    m = air.get("muas") or {}
    L = [f"# {doc.get('name', name)} (`{name}`)", "",
         f"Generated by `python -m aeroplan show {name} --md`. Do not edit. Source: `aircraft/{name}/`.", "",
         f"Version {acft.version}. Built {build.get('built', '-')} (author: {build.get('author', '-')}). "
         f"Kind: {acft.info.get('kind', 'aircraft')}. Consumers: {', '.join(acft.info.get('consumers') or []) or '-'}.", ""]

    L += ["## Mass properties", ""]
    mp = m.get("mass_properties")
    if mp:
        i = mp["inertia"]
        L += _table(["Quantity", "Value"], [
            ["Mass", _num(mp["mass"])], ["CG (design frame)", _xyz(mp["cg"]["xyz"]) + " m"],
            ["Ixx, Iyy, Izz", f"{i['ixx']:.4g}, {i['iyy']:.4g}, {i['izz']:.4g} {i['units']}"],
            ["Ixy, Ixz, Iyz", f"{i['ixy']:.3g}, {i['ixz']:.3g}, {i['iyz']:.3g} {i['units']}"],
            ["Source", f"{mp.get('source', '-')}{' (placeholder)' if mp.get('placeholder') else ''}"]])
    else:
        L += ["The aircraft has no mass properties.", ""]
    ref = m.get("reference")
    if ref:
        L += ["## Reference", ""]
        L += _table(["Quantity", "Value"], [["S", _num(ref.get("s_ref"))], ["b", _num(ref.get("b_ref"))],
                                             ["c", _num(ref.get("c_ref"))], ["Kind", ref.get("kind", "fixed wing")]])

    rows = _planforms(doc)
    if rows:
        L += ["## Lifting surfaces", ""]
        L += _table(["Surface", "Kind", "Span (m)", "Area (m^2)", "Root chord (m)", "Tip chord (m)", "Placeholder"], rows)
    rows = _propellers(doc)
    if rows:
        L += ["## " + ("Hubs and rotors" if (ref or {}).get("kind") == "multirotor" else "Propellers"), ""]
        L += _table(["Item", "Role", "Motor", "Hub (m)", "Spin", "Diameter"], rows)

    L += ["## Propulsion system", ""]
    systems = _systems(doc)
    if systems:
        for ps in systems:
            mo, esc, bat = ps.get("motor") or {}, ps.get("esc") or {}, ps.get("battery") or {}
            L += _table(["Item", "Value"], [
                ["System", f"`{ps['system_id']}` (basis {ps.get('basis', '-')})"], ["Motor", mo.get("model", "-")],
                ["ESC", esc.get("model", "-")],
                ["Battery", f"{bat.get('model', '-')}, {bat.get('cells_s', '-')}S{bat.get('cells_p', '-')}P"],
                ["Propeller", f"{ps.get('model', '-')}, {_num(ps.get('diameter'))}, {ps.get('blades', '-')} blades"],
                ["Maximum shaft power", f"{ps['p_max']['value']:.0f} W" if ps.get("p_max") else "-"]])
    else:
        L += ["The aircraft has no propulsion system record.", ""]

    L += ["## Datasets", ""]
    ds = [e for e in assets.register(doc, create=False) if e["kind"] == "dataset"]
    if ds:
        L += _table(["Name", "Role", "Tool", "Fidelity", "Hash"], [
            [f"`{e['name']}`", e["role"], e["tool"], str((e.get("dataset") or {}).get("fidelity", "-")), e["id"][13:25]]
            for e in ds])
    else:
        L += ["The aircraft has no dataset.", ""]
    nfile = sum(1 for e in assets.register(doc, create=False) if e["kind"] == "file")
    L += [f"Raw file assets in the register: {nfile}.", ""]

    ph = placeholders(doc)
    L += ["## Placeholders", "", f"{len(ph)} values are marked placeholder. List them with "
          f"`python -m aeroplan show {name} --placeholders`.", ""]
    return "\n".join(L)
